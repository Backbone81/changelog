package changelog

import (
	"fmt"
	"gopkg.in/yaml.v2"
	"io/ioutil"
	"path/filepath"
)

const ConfigFilename = ".changelog.yaml"

type Config struct {
	// BaseDir contains the directory where the config file was loaded from, is not serialized into the config file
	BaseDir string `yaml:"-"`

	// ChangelogDir contains the subdirectory of BaseDir where the changelogs are placed in
	ChangelogDir string `yaml:"changelogDir"`

	// CatalogFileName contains the name of the catalog file in the ChangelogDir
	CatalogFileName string `yaml:"catalogFileName"`

	// UnreleasedDir contains the subdirectory of ChangelogDir which holds all unreleased changelog entries
	UnreleasedDir string `yaml:"unreleasedDir"`

	// UnreleasedFilePattern contains the time.Format string for the unreleased changelog entry files
	UnreleasedFilePattern string `yaml:"unreleasedFilePattern"`

	// ChangelogFileName contains the filename for the end user changelog file in the BaseDir
	ChangelogFileName string `yaml:"changelogFileName"`

	// Template contains the go template to use for rendering the end user changelog file
	Template string `yaml:"template"`
}

var DefaultConfig = Config{
	ChangelogDir:          "changelog",
	CatalogFileName:       "changelog.yaml",
	UnreleasedDir:         "unreleased",
	UnreleasedFilePattern: "changelog-20060201-150405",
	ChangelogFileName:     "CHANGELOG.md",
	Template: `# Changelog
**Note:** This file is automatically generated. Do not edit by hand.

## Unreleased
{{range .Catalog.Unreleased}}- {{.Description | trim}}
{{end}}
{{range .Catalog.Releases}}## {{.Version | trim}} ({{.Date.Format "2006-01-02"}})
{{range .Entries}}- {{.Description | trim}}
{{end}}
{{end}}`,
}

func (c *Config) loadFromFile(filePath string) error {
	data, err := ioutil.ReadFile(filePath)
	if err != nil {
		return fmt.Errorf("failed to read config file; %w", err)
	}

	var config Config
	if err := yaml.Unmarshal(data, &config); err != nil {
		return fmt.Errorf("failed to unmarshal config file; %w", err)
	}

	*c = config
	return nil
}

func (c *Config) saveToFile(filePath string) error {
	data, err := yaml.Marshal(*c)
	if err != nil {
		return fmt.Errorf("failed to marshal config; %w", err)
	}

	if err := ioutil.WriteFile(filePath, data, 0666); err != nil {
		return fmt.Errorf("failed to write config file; %w", err)
	}

	return nil
}

func (c *Config) LoadFromDir(directory string) error {
	filePath := filepath.Join(directory, ConfigFilename)
	if err := c.loadFromFile(filePath); err != nil {
		parentDir := filepath.Dir(directory)
		if parentDir != directory {
			// move up the directory tree in search for a config file
			return c.LoadFromDir(parentDir)
		}
		return err
	}
	c.BaseDir = directory
	return nil
}
